"""Blind prespecified T0/T1 continuation controls, with genuine teacher histories."""

import argparse
import json
import random
from pathlib import Path

import numpy as np
import soundfile as sf

from latent_diaries.feature_provenance import checksum


def main():
    p = argparse.ArgumentParser(description=__doc__)
    for name in ["corpus", "teachers", "mapping", "t0-results", "t1-results", "output-dir"]:
        p.add_argument("--" + name, type=Path, required=True)
    args = p.parse_args()
    if args.output_dir.exists():
        raise ValueError("Fresh listening directory required")
    corpus = json.loads(args.corpus.read_text())
    teachers = json.loads(args.teachers.read_text())
    if teachers["corpus_sha256"] != checksum(args.corpus):
        raise ValueError("Teacher/corpus provenance differs")
    stories = {r["id"]: r for r in corpus["rows"]}
    audio = {r["id"]: r for r in teachers["records"]}
    mapping = {r["id"]: r for r in json.loads(args.mapping.read_text())}
    items = []
    for mode, file in [("t0", args.t0_results), ("t1", args.t1_results)]:
        results = json.loads(file.read_text())
        if results["text_used"] or results["teacher_targets_read"]:
            raise ValueError("Student must use media vectors and learned weights only")
        for result in results["records"]:
            row = mapping[result["id"]]
            if row["kind"] in {"matched", "same-image"}:
                items.append({"mode": mode, **row, "student": result})
    if len(items) != 12 or len({r["sequence_id"] for r in items}) != 4:
        raise ValueError("Exactly12 prespecified controls across4 source sequences required")
    random.Random(2026101605).shuffle(items)
    args.output_dir.mkdir(mode=0o700)
    review = []
    private = []
    for i, item in enumerate(items, 1):
        source = stories[item["sequence_id"]]
        history = audio[item["history_sequence_id"] + "-f1"]
        if (
            checksum(source["image"]) != source["image_sha256"]
            or checksum(history["audio"]) != history["audio_sha256"]
        ):
            raise ValueError("Private source changed")
        if item["student"]["audio"] is None:
            raise ValueError("Empty student control retained; cannot manufacture listening audio")
        if checksum(item["student"]["audio"]) != item["student"]["audio_sha256"]:
            raise ValueError("Generated student audio changed")
        waves = []
        for path in [history["audio"], item["student"]["audio"]]:
            wave, rate = sf.read(path, dtype="float32")
            if rate != 24000 or wave.ndim != 1 or not np.isfinite(wave).all():
                raise ValueError("Finite mono24kHz genuine audio required")
            waves.append(wave)
        label = f"TB-{i:02d}"
        file = args.output_dir / (label + ".wav")
        sf.write(file, np.concatenate([waves[0], np.zeros(10800, dtype=np.float32), waves[1]]), 24000)
        clip_id = f"asfl-bridge-20261016-{i:02d}"
        review.append(
            {
                "id": clip_id,
                "run_id": "asfl-bridge-20261016",
                "blind_label": label,
                "image": source["image"],
                "audio": file.name,
            }
        )
        private.append(
            {
                "clip_id": clip_id,
                **item,
                "audio_sha256": checksum(file),
                "teacher_history": history["audio"],
                "student_starts_at": len(waves[0]) / 24000 + 0.45,
            }
        )
    (args.output_dir / "review.jsonl").write_text("".join(json.dumps(r) + "\n" for r in review))
    (args.output_dir / "private-mapping.json").write_text(
        json.dumps(
            {
                "scope": "First fragment is teacher audio; second is generated by a textless continuation reader. Not autonomous rollout.",
                "source_sha256": checksum(__file__),
                "corpus_sha256": checksum(args.corpus),
                "mapping": private,
                "human_ratings_created": 0,
            },
            indent=2,
        )
        + "\n"
    )
    print("Prepared12 blinded teacher-history/student-continuation pairs; no ratings created")


if __name__ == "__main__":
    main()
